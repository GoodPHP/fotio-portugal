/**
 * Image slots, and the paths derived from them.
 *
 * A "slot" is a position on the site that holds a photograph — `cities/lisboa`,
 * `portfolio/wedding/2` — and it is the key everything else is derived from:
 * the rendered AVIF and WebP files, the share card, and the credit entry. The
 * slots themselves are declared in `scripts/photos/targets.ts` and derived from
 * the catalogue, so a place or a service cannot exist without one.
 *
 * Paths are not stored on the catalogue data. They are computed here, and the
 * files are listed in `src/lib/data/image-manifest.ts`, which is generated by
 * `npm run photos:fetch`.
 */
import { IMAGE_SLOTS } from './data/image-manifest';
import { SITE_URL } from './site';

/** Root-relative path to the branded fallback OG image (1200×630). */
export const DEFAULT_OG_IMAGE = '/og-default.png';
export const DEFAULT_OG_IMAGE_WIDTH = 1200;
export const DEFAULT_OG_IMAGE_HEIGHT = 630;

/** The slot holding a place's hero photograph. */
export function citySlot(slug: string): string {
  return `cities/${slug}`;
}

/** The slot holding a service's card photograph. */
export function serviceSlot(slug: string): string {
  return `services/${slug}`;
}

/** One frame of a place's gallery, 1-indexed. */
export function gallerySlot(citySlug: string, index: number): string {
  return `gallery/${citySlug}/${index}`;
}

/**
 * The 1200×630 JPEG share card for a slot, or the branded default.
 *
 * JPEG rather than the AVIF the page itself serves, because social scrapers do
 * not negotiate a `<picture>` and several of them decode nothing newer.
 */
export function ogImagePath(slot: string): string {
  return IMAGE_SLOTS[slot]?.og ?? DEFAULT_OG_IMAGE;
}

/**
 * Frames the photo pipeline filed under the wrong place, checked by eye: a
 * river bridge under the Azores, Lisbon rooftops under Braga, Bom Jesus (in
 * Braga) under Coimbra, the Carmo ruins and the Santa Justa lift (both in
 * Lisbon) under Évora. Treated as missing until `npm run photos:select`
 * replaces them — a page captioned with one place and showing another is the
 * quickest way to lose a visitor who has been there.
 */
const MISPLACED_SLOTS = new Set([
  'gallery/acores/2',
  'gallery/braga/1',
  'gallery/braga/2',
  'gallery/coimbra/3',
  'gallery/evora/1',
  'gallery/evora/4',
]);

/** Whether a slot has a photograph at all — one that shows what it claims to. */
export function hasImage(slot: string): boolean {
  return slot in IMAGE_SLOTS && !MISPLACED_SLOTS.has(slot);
}

/**
 * The largest rendered file for a slot, as a root-relative path, for markup
 * that needs a real image URL (ImageGallery, Person). A slot key is not a
 * path: the gallery markup used to publish `https://…/portfolio/couple/1`,
 * which is nothing.
 */
export function imagePath(slot: string): string | undefined {
  const sources = IMAGE_SLOTS[slot]?.webp;
  return sources?.[sources.length - 1]?.path;
}

/** Turn a root-relative (or already-absolute) image path into an absolute URL. */
export function absoluteOgImage(path: string): string {
  if (/^https?:\/\//.test(path)) return path;
  return `${SITE_URL}${path.startsWith('/') ? '' : '/'}${path}`;
}
