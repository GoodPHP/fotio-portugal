/**
 * Fully prerendered, and nothing else is served.
 *
 * The catalogue is hardcoded TypeScript. The only time-dependent input is the
 * drip schedule, and that is a pure function of (identity, now) whose answer
 * changes at most once a day — so ISR was revalidating a page hourly to
 * discover that nothing had changed. It was also actively wrong: the sitemap
 * is written at build time while pages revalidated hourly, so between deploys
 * the two disagreed about what was published. Generated by the same build,
 * they cannot.
 *
 * Releasing the next batch of drip-published pages is therefore a rebuild
 * rather than a revalidation.
 */
export const dynamic = 'force-static';
export const dynamicParams = false;

interface LeafPageProps {
  params: Promise<{ locale: Locale; service: string; city: string }>;
}

/**
 * `[locale]/layout.tsx` declares its own generateStaticParams, so Next runs this
 * once per locale and hands the parent's params in. That matters here: the
 * service slug differs per language, and a locale-blind list would prerender
 * /fr/services/wedding/paris — a path the French middleware never rewrites to,
 * leaving every real French leaf to fall through to on-demand rendering.
 */
export function generateStaticParams({ params }: { params: { locale: string } }) {
  if (!isLocale(params.locale)) return [];
  return publishedLeafParams(params.locale);
}

export async function generateMetadata({ params }: LeafPageProps): Promise<Metadata> {
  const { locale, service: serviceParam, city: citySlug } = await params;
  const city = getCity(citySlug);
  const service = getServiceBySlug(serviceParam, locale);
  if (!city || !service) return {};

  const { title, description } = getSeoMetadata(city, service, locale);
  return buildMetadata({
    locale,
    route: '/services/[service]/[city]',
    alternates: leafAlternateParams(service, city),
    // Combinations we have not written for are real pages, but they are
    // composed from templates and do not deserve an index slot.
    noindex: !isCuratedLeaf(service.slug, city.slug, locale),
    title,
    description,
    ogImage: ogImagePath(serviceSlot(service.slug)),
    ogImageAlt: `${tx(service.name, locale)} · ${city.name}`,
  });
}

export default async function LeafPage({ params }: LeafPageProps) {
  const { locale, service: serviceParam, city: citySlug } = await params;
  setRequestLocale(locale);

  const city = getCity(citySlug);
  const service = getServiceBySlug(serviceParam, locale);
  // An unknown slug, or a slug belonging to the other locale, is not a page.
  if (!city || !service) notFound();
  // Not yet at its drip-publish slot → behave as if it does not exist.
  if (!isLeafPublished(service.slug, city.slug)) notFound();

  const serviceName = tx(service.name, locale);
  const region = tx(city.region, locale);
  const content = generateProgrammaticContent(city, service, locale);

  const cityLabel = localizedCityName(city, locale);

  const labels = {
    answerEyebrow: { en: 'In short', pt: 'Em resumo' }[locale],
    breadcrumbHome: { en: 'Home', pt: 'Início' }[locale],
    breadcrumbServices: { en: 'Sessions', pt: 'Sessões' }[locale],
    delivery: { en: 'Gallery delivery', pt: 'Entrega da galeria' }[locale],
    ctaHeading: {
      en: `${serviceName} ${inPlace(city, 'en')}, from ${formatPrice(service.initialPrice, 'en')}`,
      pt: `${serviceName} ${inPlace(city, 'pt')}, desde ${formatPrice(service.initialPrice, 'pt')}`,
    }[locale],
    ctaText: {
      en: `Tell us your date and we’ll match you with a local photographer. ${tx(REPLY_TIME, 'en')}`,
      pt: `Diga-nos a data e encontramos um fotógrafo local. ${tx(REPLY_TIME, 'pt')}`,
    }[locale],
    aboutTitle: {
      en: `Why choose ${serviceName} ${inPlace(city, 'en')}?`,
      pt: `Porquê ${serviceName.toLowerCase()} ${ptAt(city)}?`,
    }[locale],
    routeTitle: {
      en: `What does the session ${inPlace(city, 'en')} look like?`,
      pt: `Como decorre a sessão ${ptAt(city)}?`,
    }[locale],
    detailsTitle: { en: 'What does the package include?', pt: 'O que inclui o pacote?' }[locale],
    faqTitle: {
      en: `FAQ — ${serviceName} ${inPlace(city, 'en')}`,
      pt: `Perguntas frequentes — ${serviceName.toLowerCase()} ${ptAt(city)}`,
    }[locale],
    from: { en: 'Starting from', pt: 'Desde' }[locale],
    duration: { en: 'Duration', pt: 'Duração' }[locale],
    photos: { en: 'Edited photos', pt: 'Fotografias editadas' }[locale],
    book: checkAvailabilityIn(city, locale),
    whatsapp: tx(CTA.chatWhatsapp, locale),
    portfolioEyebrow: { en: 'Portfolio', pt: 'Portefólio' }[locale],
    portfolioTitle: {
      en: `${serviceName} ${inPlace(city, 'en')}`,
      pt: `${serviceName} ${ptAt(city)}`,
    }[locale],
    portfolioSubtitle: {
      en: `A selection of ${serviceName.toLowerCase()} shots to inspire your session.`,
      pt: `Uma selecção de fotografias de ${serviceName.toLowerCase()} para inspirar a sua sessão.`,
    }[locale],
    relatedServicesTitle: {
      en: `Other services ${inPlace(city, 'en')}`,
      pt: `Outros serviços ${ptAt(city)}`,
    }[locale],
    nearbyTitle: {
      en: `${serviceName} in other cities`,
      pt: `${serviceName} noutras cidades`,
    }[locale],
  };

  const waHref = whatsappBookingLink({ where: cityLabel, session: serviceName }, locale);
  const track = { context: 'leaf-price-card', service: service.slug, city: city.slug };

  // Related: other tailored services in the same city (published leaves only),
  // offered in this language — a city's topServices mix English-only and
  // Portuguese-only sessions, whose leaves 404 in the other locale.
  const relatedServices = city.topServices
    .filter((slug) => slug !== service.slug && isLeafPublished(slug, city.slug))
    .map((slug) => getServiceById(slug))
    .filter((s): s is NonNullable<typeof s> => Boolean(s) && serviceExistsIn(s!, locale))
    .slice(0, 6);

  // Nearby: same service in other cities that prioritise it, then any others —
  // restricted to leaves that are already published so links never 404.
  const prioritised = CITIES.filter((c) => c.slug !== city.slug && c.topServices.includes(service.slug) && isLeafPublished(service.slug, c.slug));
  const fallbackCities = CITIES.filter((c) => c.slug !== city.slug && !c.topServices.includes(service.slug) && isLeafPublished(service.slug, c.slug));
  const nearbyCities = [...prioritised, ...fallbackCities].slice(0, 6);

  // Per-service portfolio gallery (empty until stock photos are fetched).
  const portfolio = portfolioImages(service.slug);

  const url = absoluteUrl(locale, '/services/[service]/[city]', { service: serviceSlug(service, locale), city: city.slug });
  const { title: metaTitle, description: metaDescription } = getSeoMetadata(city, service, locale);
  const jsonLd = graph([
    webPageNode({
      url,
      name: metaTitle,
      description: metaDescription,
      locale,
      image: absoluteOgImage(ogImagePath(serviceSlot(service.slug))),
    }),
    professionalServiceNode({
      citySlug: city.slug,
      cityName: city.name,
      region,
      locale,
      url,
      // Same coverage claim as the city page makes, so the two agree.
      coveredAreas: city.coveredAreas,
      image: absoluteOgImage(ogImagePath(citySlot(city.slug))),
    }),
    serviceOfferNode({
      serviceSlug: service.slug,
      serviceName,
      description: content.answerBox,
      price: service.initialPrice,
      locale,
      url,
      citySlug: city.slug,
      areaServedName: city.name,
    }),
    faqNode(content.customFAQs),
    breadcrumbNode([
      { name: labels.breadcrumbHome, url: absoluteUrl(locale, '/') },
      { name: labels.breadcrumbServices, url: absoluteUrl(locale, '/services') },
      { name: serviceName, url: absoluteUrl(locale, '/services/[service]', { service: serviceSlug(service, locale) }) },
      { name: cityLabel, url },
    ]),
  ]);

  return (
    <CityTheme theme={city.theme}>
      <main>
      <JsonLd data={jsonLd} />

      <div className="mx-auto max-w-[92rem] px-6 pt-12 lg:pt-16">
        <Breadcrumbs
          items={[
            { name: labels.breadcrumbHome, href: '/' },
            { name: labels.breadcrumbServices, href: '/services' },
            { name: serviceName, href: serviceHref(service, locale) },
            { name: cityLabel },
          ]}
        />
      </div>

      <div className="mx-auto grid max-w-[92rem] gap-12 px-6 pb-12 pt-6 lg:grid-cols-12">
        {/* Main content */}
        <article className="lg:col-span-7 xl:col-span-8">
          <FadeIn instant>
            <p className="eyebrow">{region}</p>
            <h1 className="mt-3 font-display text-4xl font-bold leading-[1.08] tracking-tight text-brand-dark sm:text-5xl">
              {serviceName} <span className="text-brand-muted">{inPlace(city, locale)}</span>
            </h1>
          </FadeIn>

          {/* Answer-first highlighted block */}
          <FadeIn instant delay={0.08}>
            <div className="mt-8 rounded-card-sm border border-brand-orange/20 bg-brand-orange/5 p-6 sm:p-8">
              <p className="eyebrow">{labels.answerEyebrow}</p>
              <p className="mt-3 text-lg leading-relaxed text-brand-dark">{content.answerBox}</p>
            </div>
          </FadeIn>

          <FadeIn instant delay={0.05} className="mt-12">
            <h2 className="font-display text-2xl font-bold tracking-tight text-brand-dark sm:text-3xl">{labels.aboutTitle}</h2>
            <p className="mt-4 text-base leading-relaxed text-brand-dark">{content.introParagraph}</p>
            {/*
              When, rather than where. Composed from this city's spot hours and
              this service's duration, so it differs across the matrix instead of
              repeating one sentence on a hundred and twenty-five pages.
            */}
            <p className="mt-4 text-base leading-relaxed text-brand-dark">{content.timingParagraph}</p>
          </FadeIn>

          <FadeIn delay={0.05} className="mt-10">
            <h2 className="font-display text-2xl font-bold tracking-tight text-brand-dark sm:text-3xl">{labels.routeTitle}</h2>
            <p className="mt-4 text-base leading-relaxed text-brand-dark">{content.sampleRoute}</p>
          </FadeIn>

          <FadeIn delay={0.05} className="mt-10">
            <h2 className="font-display text-2xl font-bold tracking-tight text-brand-dark sm:text-3xl">{labels.detailsTitle}</h2>
            <p className="mt-4 text-base leading-relaxed text-brand-dark">{content.detailsText}</p>
          </FadeIn>

          {/*
            The only FAQ on the site that is not the shared <Faq> section: this
            one lives inside the article column of a two-column page, and the
            shared component is a full-width band. It uses the same disclosure
            primitives, so the marker and the open behaviour still come from
            one place.
          */}
          {content.customFAQs.length > 0 && (
            <FadeIn delay={0.05} className="mt-12">
              <h2 className="font-display text-2xl font-bold text-brand-dark sm:text-3xl">{labels.faqTitle}</h2>
              <div className="mt-6 border-t border-brand-rule">
                {content.customFAQs.map((faq) => (
                  <details key={faq.question} className="disclosure group border-b border-brand-rule">
                    <summary className="flex items-center justify-between gap-5 py-5 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brand-orange-deep">
                      <span className="font-display text-lg font-semibold text-brand-dark transition-colors group-hover:text-brand-orange-deep">
                        {faq.question}
                      </span>
                      <span className="disclosure-mark" aria-hidden="true">
                        <svg className="h-3 w-3" viewBox="0 0 12 12" fill="none">
                          <path d="M6 1v10M1 6h10" stroke="currentColor" strokeWidth="1.6" strokeLinecap="square" />
                        </svg>
                      </span>
                    </summary>
                    <p className="pb-5 text-[0.9375rem] leading-relaxed text-brand-muted">{faq.answer}</p>
                  </details>
                ))}
              </div>
            </FadeIn>
          )}
        </article>

        {/* Sticky price + CTA */}
        <aside aria-label="Booking" className="lg:col-span-5 xl:col-span-4">
          <div data-surface="dark" className="sticky top-24 rounded-card bg-brand-dark p-8 text-white">
            <p className="text-sm text-brand-muted">{labels.from}</p>
            <p className="mt-1 font-display text-5xl font-bold">{formatPrice(service.initialPrice, locale)}</p>

            <dl className="mt-8 space-y-4 border-t border-white/10 pt-6">
              <div className="flex items-center justify-between">
                <dt className="text-sm text-brand-muted">{labels.duration}</dt>
                <dd className="font-semibold">{formatDuration(service.durationMinutes, locale)}</dd>
              </div>
              <div className="flex items-center justify-between">
                <dt className="text-sm text-brand-muted">{labels.photos}</dt>
                <dd className="font-semibold">{formatPhotoCount(service)}</dd>
              </div>
              <div className="flex items-center justify-between">
                <dt className="text-sm text-brand-muted">{labels.delivery}</dt>
                <dd className="font-semibold">{formatDelivery(service.deliveryHours, locale)}</dd>
              </div>
            </dl>
            <p className="mt-5 text-xs leading-relaxed text-brand-muted">{tx(FROM_PRICE.body, locale)}</p>

            <Link
              href={bookHref({ service, city })}
              className="btn btn-primary mt-6 w-full focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-white"
              {...trackAttrs('cta_check_availability', track)}
            >
              {labels.book}
            </Link>
            <a
              href={waHref}
              target="_blank"
              rel="noopener noreferrer"
              className="btn btn-outline mt-3 w-full focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-white"
              {...trackAttrs('whatsapp_clicked', track)}
            >
              <WhatsAppIcon />
              {labels.whatsapp}
            </a>
          </div>
        </aside>
      </div>

      {/* Service portfolio gallery */}
      <PortfolioGrid
        priorityFeatured
        images={portfolio}
        eyebrow={labels.portfolioEyebrow}
        title={labels.portfolioTitle}
        subtitle={labels.portfolioSubtitle}
        alt={`${serviceName} · ${cityLabel}`}
        locale={locale}
      />

      {/* Related services in this city */}
      {relatedServices.length > 0 && (
        <section aria-labelledby="related-services-heading" className="bg-brand-sand py-16">
          <div className="mx-auto max-w-[92rem] px-6">
            <FadeIn>
              <h2 id="related-services-heading" className="font-display text-2xl font-bold tracking-tight text-brand-dark sm:text-3xl">
                {labels.relatedServicesTitle}
              </h2>
            </FadeIn>
            <div className="mt-8 grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
              {relatedServices.map((related) => (
                <Link
                  key={related.slug}
                  href={leafHref(related, city, locale)}
                  className="bento-card group flex items-center justify-between gap-4 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brand-orange-deep"
                >
                  <span>
                    <span className="block font-display text-lg font-semibold text-brand-dark">{tx(related.name, locale)}</span>
                    <span className="block text-sm text-brand-muted">{labels.from} {formatPrice(related.initialPrice, locale)}</span>
                  </span>
                  <span className="text-brand-muted transition-colors group-hover:text-brand-orange-deep" aria-hidden="true">→</span>
                </Link>
              ))}
            </div>
          </div>
        </section>
      )}

      {/* Same service in nearby cities */}
      {nearbyCities.length > 0 && (
        <section aria-labelledby="nearby-heading" className="mx-auto max-w-[92rem] px-6 py-16">
          <FadeIn>
            <h2 id="nearby-heading" className="font-display text-2xl font-bold tracking-tight text-brand-dark sm:text-3xl">
              {labels.nearbyTitle}
            </h2>
          </FadeIn>
          <div className="mt-8 grid grid-cols-2 gap-4 sm:grid-cols-3 lg:grid-cols-6">
            {nearbyCities.map((nearby) => (
              <Link
                key={nearby.slug}
                href={leafHref(service, nearby, locale)}
                className="group flex items-center justify-between rounded-chip border border-brand-rule bg-brand-tile px-4 py-4 transition-all hover:border-brand-orange/30 focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brand-orange-deep"
              >
                <span className="font-display font-semibold text-brand-dark">{localizedCityName(nearby, locale)}</span>
                <span className="text-brand-muted transition-colors group-hover:text-brand-orange-deep" aria-hidden="true">→</span>
              </Link>
            ))}
          </div>
        </section>
      )}

      <CtaBand
        headingId="leaf-cta-heading"
        heading={labels.ctaHeading}
        text={labels.ctaText}
        locale={locale}
        context="leaf-final"
        service={service}
        city={city}
        primaryLabel={labels.book}
      />
      </main>
    </CityTheme>
  );
}
